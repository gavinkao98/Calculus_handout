// Pick the Noto Serif TC unicode-range subsets that Q7's Chinese strings need,
// and write src/q7/cjkFaces.ts (static imports → only those woff2 files are bundled).
//   node scripts/cjk-subsets.mjs        (run in paper/; rerun after editing src/q7/zh.ts)
import fs from "node:fs";
import path from "node:path";

const WEIGHTS = ["400", "500"];
const PKG = "node_modules/@fontsource/noto-serif-tc";

const src = fs.readFileSync("src/q7/zh.ts", "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
const chars = [...new Set([...src].filter((c) => c.codePointAt(0) > 0x7f))].sort();

const parseRange = (s) =>
  s.split(",").map((r) => {
    const [a, b] = r.trim().replace(/^U\+/i, "").split("-");
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  });

const out = [];
for (const w of WEIGHTS) {
  const css = fs.readFileSync(path.join(PKG, `${w}.css`), "utf8");
  const blocks = [...css.matchAll(/url\(\.\/files\/([^)]+?\.woff2)\)[\s\S]*?unicode-range:\s*([^;]+);/g)].map((m) => ({
    file: m[1],
    range: m[2].trim(),
    spans: parseRange(m[2]),
  }));
  const need = new Map();
  for (const c of chars) {
    const cp = c.codePointAt(0);
    const b = blocks.find((b) => b.spans.some(([lo, hi]) => cp >= lo && cp <= hi));
    if (!b) throw new Error(`no Noto Serif TC ${w} subset covers "${c}" (U+${cp.toString(16)})`);
    need.set(b.file, b);
  }
  for (const b of need.values()) out.push({ w, ...b });
}

const id = (f) => "f_" + f.replace(/^noto-serif-tc-/, "").replace(/-normal\.woff2$/, "").replace(/-/g, "_");
let ts = `// GENERATED by scripts/cjk-subsets.mjs from src/q7/zh.ts — do not edit by hand.\n`;
ts += `// ${chars.length} distinct non-ASCII characters → ${out.length} subset files (weights ${WEIGHTS.join(", ")}).\n`;
for (const o of out) ts += `import ${id(o.file)} from "@fontsource/noto-serif-tc/files/${o.file}";\n`;
ts += `\nexport const CJK_FACES: Array<{ url: string; weight: string; unicodeRange: string }> = [\n`;
for (const o of out) ts += `  { url: ${id(o.file)}, weight: "${o.w}", unicodeRange: "${o.range}" },\n`;
ts += `];\n`;
fs.writeFileSync("src/q7/cjkFaces.ts", ts);

let bytes = 0;
for (const o of out) bytes += fs.statSync(path.join(PKG, "files", o.file)).size;
console.log(`${chars.length} chars → ${out.length} files, ${(bytes / 1024).toFixed(1)} KiB`);
for (const o of out) console.log(`  ${o.w}  ${o.file}`);
